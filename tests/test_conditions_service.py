"""Application Service tests for declare_conditions/load_conditions/
list_conditions - Increment 019, Checkpoint 2 (Service).

Covers the service-owned scenarios from the normative matrix
(INCREMENT_019_FINAL_SPECIFICATION.md, Section 25.2): T-048-T-069. Also
closes CP1-N1 (declared_at generated by declare_conditions is UTC), noted
by the Checkpoint 1 micro-review as a Checkpoint-2 obligation rather than a
Checkpoint-1 gap.

Every `# T-NNN` tag below names the scenario the tagged test *actually*
exercises, reconciled against Section 25.2's own description of that
number - not merely a sequential label. Reconciliation performed for the
Checkpoint 2 correction task, following CP2-M1 of
INCREMENT_019_CHECKPOINT_2_MICRO_REVIEW.md: ~16 of the file's original 22
tags named the wrong scenario (each test was real and passing, but proved
a different T-NNN than the one printed next to it), and four scenarios -
T-052, T-054, T-058, T-060 - had no test at all under any label. A fifth,
T-066, had a tag but the tagged test actually proved part of T-065's own
guarantee instead. All six are corrected/added below. A handful of tests
that exercise real, useful behavior with no scenario of their own in this
range are kept and marked "additional coverage", never given a
T-NNN they do not actually prove.

No CLI and no activity-logging boundary concerns belong here beyond the
Application Service's own intrinsic best-effort logging calls (Section
19.1/23 of the frozen spec assigns T-067-T-069 to this exact layer) - the
CLI itself, and confirmation that the CLI never double-logs, remain
Checkpoint 3's responsibility.
"""

from datetime import datetime, timezone
from decimal import Decimal

import pytest
from pydantic import ValidationError

from molecular.conditions import PhDeclaration, PhPoint
from molecular.conditions_registry import ConditionsRecordInvalidError, _conditions_dir
from molecular.conditions_service import (
    ConditionsDeclarationConflictError,
    ConditionsPersistenceError,
    ConditionsPredecessorNotFoundError,
    ConditionsValidationError,
    declare_conditions,
    list_conditions,
    load_conditions,
)


def _point(value) -> PhDeclaration:
    return PhDeclaration(point=PhPoint(value=value))


def _declare(project_dir, **overrides):
    defaults = dict(
        conditions_id="ph-standard-001",
        ph=_point(Decimal("7.4")),
        purpose="simulation_input",
        declared_by="Dr. Jane Doe",
    )
    defaults.update(overrides)
    return declare_conditions(project_dir, **defaults)


def _activity_lines(project_dir) -> list:
    log_file = project_dir / "logs" / "activity.log"
    return log_file.read_text(encoding="utf-8").splitlines()


