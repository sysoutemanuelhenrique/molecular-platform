def test_three_level_revision_chain_persists_all_three(tmp_path):  # T-060
    a = _declare(tmp_path, conditions_id="ph-a-001", ph=_point(Decimal("6.0")))
    b = _declare(
        tmp_path,
        conditions_id="ph-b-001",
        supersedes_id="ph-a-001",
        ph=_point(Decimal("7.0")),
    )
    c = _declare(
        tmp_path,
        conditions_id="ph-c-001",
        supersedes_id="ph-b-001",
        ph=_point(Decimal("8.0")),
    )

    assert a.supersedes_id is None
    assert b.supersedes_id == a.id
    assert c.supersedes_id == b.id

    # Every link remains independently loadable, immutable, and none is
    # ever rewritten retroactively by a later call in the chain.
    reloaded_a = load_conditions(tmp_path, a.id)
    reloaded_b = load_conditions(tmp_path, b.id)
    reloaded_c = load_conditions(tmp_path, c.id)
    assert reloaded_a == a
    assert reloaded_b == b
    assert reloaded_c == c
    assert reloaded_a.supersedes_id is None
    assert reloaded_b.supersedes_id == a.id
    assert reloaded_c.supersedes_id == b.id


