"""Application Service tests for declare_conditions/load_conditions/
list_conditions - Increment 019, Checkpoint 2 (Service).

Covers the service-owned scenarios from the normative matrix
(INCREMENT_019_FINAL_SPECIFICATION.md, Section 25.2): T-048-T-069. Also
closes CP1-N1 (declared_at generated by declare_conditions is UTC), noted
by the Checkpoint 1 micro-review as a Checkpoint-2 obligation rather than a
Checkpoint-1 gap.

No CLI and no activity-logging boundary concerns belong here beyond the
Application Service's own intrinsic best-effort logging calls (Section
19.1/23 of the frozen spec assigns T-067-T-069 to this exact layer) - the
CLI itself, and confirmation that the CLI never double-logs, remain
Checkpoint 3's responsibility.
"""

from datetime import datetime, timezone
from decimal import Decimal
from pathlib import Path

import pytest
from pydantic import ValidationError

from molecular.conditions import PhDeclaration, PhPoint, PhRange
from molecular.conditions_registry import ConditionsRecordInvalidError, _conditions_dir
from molecular.conditions_service import (
    ConditionsActivityDetails,
    ConditionsDeclarationConflictError,
    ConditionsPersistenceError,
    ConditionsPredecessorNotFoundError,
    ConditionsValidationError,
    declare_conditions,
    list_conditions,
    load_conditions,
)


def _point(value) -> PhDeclaration:
    return PhDeclaration(point=PhPoint(value=value))


def _declare(tmp_path, **overrides):
    defaults = dict(
        conditions_id="ph-standard-001",
        ph=_point(Decimal("7.4")),
        purpose="simulation_input",
        declared_by="Dr. Jane Doe",
    )
    defaults.update(overrides)
    return declare_conditions(tmp_path, **defaults)


def _activity_lines(tmp_path) -> list:
    log_file = tmp_path / "logs" / "activity.log"
    return log_file.read_text(encoding="utf-8").splitlines()


# --- fresh declaration (T-048-T-050) ---


def test_fresh_declaration_persists_and_returns_the_record(tmp_path):  # T-048
    declaration = _declare(tmp_path)

    assert declaration.id == "ph-standard-001"
    assert load_conditions(tmp_path, "ph-standard-001") == declaration


def test_declared_at_is_never_supplied_by_the_caller(tmp_path):  # T-049
    declaration = _declare(tmp_path)

    # declare_conditions accepts no declared_at parameter at all - the
    # signature itself enforces this (a TypeError would result from
    # attempting to pass one), so this test documents the guarantee via
    # the returned value's presence rather than a parameter probe.
    assert declaration.declared_at is not None


def test_fresh_declaration_generated_declared_at_is_utc(tmp_path):  # T-050, closes CP1-N1
    before = datetime.now(timezone.utc)
    declaration = _declare(tmp_path)
    after = datetime.now(timezone.utc)

    assert declaration.declared_at.tzinfo is not None
    assert declaration.declared_at.utcoffset().total_seconds() == 0
    assert before <= declaration.declared_at <= after


# --- idempotent retry recognition (T-051-T-056) ---


def test_exact_retry_returns_the_existing_record_unchanged(tmp_path):  # T-051
    first = _declare(tmp_path)

    retried = _declare(tmp_path)

    assert retried == first


def test_retry_never_overwrites_the_persisted_file(tmp_path):  # T-052
    first = _declare(tmp_path)
    metadata_file = _conditions_dir(tmp_path) / f"{first.id}.yaml"
    original_bytes = metadata_file.read_bytes()

    _declare(tmp_path)

    assert metadata_file.read_bytes() == original_bytes


def test_retry_does_not_require_matching_declared_at(tmp_path):  # T-053
    first = _declare(tmp_path)

    # declared_at is generated fresh on every call and is excluded from
    # the retry-equivalence comparison - the second call still recognizes
    # a safe retry despite its own freshly-generated declared_at differing
    # from the first's.
    retried = _declare(tmp_path)

    assert retried.declared_at == first.declared_at


@pytest.mark.parametrize("field,value", [
    ("ph", _point(Decimal("7.5"))),
    ("declared_by", "Dr. John Smith"),
    ("label", "a label"),
    ("rationale", "a rationale"),
])
def test_retry_with_a_divergent_field_raises_conflict(tmp_path, field, value):  # T-054
    _declare(tmp_path)

    with pytest.raises(ConditionsDeclarationConflictError):
        _declare(tmp_path, **{field: value})


def test_retry_with_a_divergent_supersedes_id_raises_conflict(tmp_path):  # T-054
    _declare(tmp_path, conditions_id="ph-original-001")
    _declare(tmp_path, conditions_id="ph-other-001")
    _declare(tmp_path, conditions_id="ph-revised-001", supersedes_id="ph-original-001")

    with pytest.raises(ConditionsDeclarationConflictError):
        _declare(tmp_path, conditions_id="ph-revised-001", supersedes_id="ph-other-001")


def test_retry_equivalence_uses_decimal_numeric_equality_not_text(tmp_path):  # T-055
    _declare(tmp_path, ph=_point(Decimal("7.40")))

    retried = _declare(tmp_path, ph=_point(Decimal("7.4")))

    assert retried.id == "ph-standard-001"


def test_retry_against_a_corrupted_existing_record_raises_record_invalid(tmp_path):  # T-056
    conditions_dir = _conditions_dir(tmp_path)
    conditions_dir.mkdir(parents=True)
    (conditions_dir / "ph-standard-001.yaml").write_text(
        "schema_version: '1.0'\nid: [unterminated\n", encoding="utf-8"
    )

    with pytest.raises(ConditionsRecordInvalidError):
        _declare(tmp_path)


# --- revision (T-057-T-063) ---


def test_revision_is_a_new_record_referencing_supersedes_id(tmp_path):  # T-057
    original = _declare(tmp_path, conditions_id="ph-original-001")

    revision = _declare(
        tmp_path, conditions_id="ph-revised-001", supersedes_id="ph-original-001"
    )

    assert revision.supersedes_id == "ph-original-001"
    assert revision.id != original.id


def test_revision_never_modifies_the_predecessor_file(tmp_path):  # T-058
    _declare(tmp_path, conditions_id="ph-original-001")
    predecessor_file = _conditions_dir(tmp_path) / "ph-original-001.yaml"
    original_bytes = predecessor_file.read_bytes()

    _declare(tmp_path, conditions_id="ph-revised-001", supersedes_id="ph-original-001")

    assert predecessor_file.read_bytes() == original_bytes


def test_revision_naming_a_nonexistent_predecessor_raises_predecessor_not_found(tmp_path):  # T-059
    with pytest.raises(ConditionsPredecessorNotFoundError):
        _declare(tmp_path, conditions_id="ph-revised-001", supersedes_id="does-not-exist")


def test_revision_naming_a_corrupted_predecessor_raises_record_invalid_not_not_found(tmp_path):  # T-060
    conditions_dir = _conditions_dir(tmp_path)
    conditions_dir.mkdir(parents=True)
    (conditions_dir / "ph-original-001.yaml").write_text(
        "schema_version: '1.0'\nid: [unterminated\n", encoding="utf-8"
    )

    with pytest.raises(ConditionsRecordInvalidError):
        _declare(tmp_path, conditions_id="ph-revised-001", supersedes_id="ph-original-001")


def test_self_supersession_rejected_as_validation_error(tmp_path):  # T-061
    with pytest.raises(ConditionsValidationError):
        _declare(tmp_path, conditions_id="ph-standard-001", supersedes_id="ph-standard-001")


def test_equivalent_revision_retry_is_recognized_as_safe(tmp_path):  # T-062
    _declare(tmp_path, conditions_id="ph-original-001")
    first_revision = _declare(
        tmp_path, conditions_id="ph-revised-001", supersedes_id="ph-original-001"
    )

    retried = _declare(
        tmp_path, conditions_id="ph-revised-001", supersedes_id="ph-original-001"
    )

    assert retried == first_revision


def test_multiple_independent_revisions_of_the_same_predecessor_are_permitted(tmp_path):  # T-063
    _declare(tmp_path, conditions_id="ph-original-001")

    first_branch = _declare(
        tmp_path, conditions_id="ph-branch-a-001", supersedes_id="ph-original-001"
    )
    second_branch = _declare(
        tmp_path, conditions_id="ph-branch-b-001", supersedes_id="ph-original-001"
    )

    assert first_branch.supersedes_id == second_branch.supersedes_id == "ph-original-001"
    assert first_branch.id != second_branch.id


# --- error taxonomy and boundaries (T-064-T-066) ---


def test_invalid_ph_raises_conditions_validation_error_with_cause(tmp_path):  # T-064
    with pytest.raises(ConditionsValidationError) as excinfo:
        declare_conditions(
            tmp_path,
            conditions_id="ph-bad-001",
            ph=_point(Decimal("7.4")),
            purpose="not_a_valid_purpose",
            declared_by="Dr. Jane Doe",
        )

    assert isinstance(excinfo.value.__cause__, ValidationError)


def test_malformed_conditions_id_raises_conditions_validation_error(tmp_path):  # T-064
    with pytest.raises(ConditionsValidationError):
        _declare(tmp_path, conditions_id="not a valid id!")


def test_unexpected_persistence_failure_raises_conditions_persistence_error(tmp_path, monkeypatch):  # T-065
    def _boom(*args, **kwargs):
        raise OSError("disk full")

    monkeypatch.setattr("molecular.conditions_registry.atomic_write_text", _boom)

    with pytest.raises(ConditionsPersistenceError) as excinfo:
        _declare(tmp_path)

    assert isinstance(excinfo.value.__cause__, OSError)


def test_persistence_failure_never_leaves_a_partial_file_behind(tmp_path, monkeypatch):  # T-066
    def _boom(*args, **kwargs):
        raise OSError("disk full")

    monkeypatch.setattr("molecular.conditions_registry.atomic_write_text", _boom)

    with pytest.raises(ConditionsPersistenceError):
        _declare(tmp_path)

    metadata_file = _conditions_dir(tmp_path) / "ph-standard-001.yaml"
    assert not metadata_file.exists()


# --- activity logging (T-067-T-069) ---


def test_successful_declaration_logs_exactly_started_then_success(tmp_path):  # T-067
    _declare(tmp_path)

    lines = _activity_lines(tmp_path)

    assert len(lines) == 2
    assert "command=conditions-declare" in lines[0]
    assert "outcome=started" in lines[0]
    assert "command=conditions-declare" in lines[1]
    assert "outcome=success" in lines[1]


def test_failed_declaration_logs_exactly_started_then_error(tmp_path):  # T-068
    with pytest.raises(ConditionsPredecessorNotFoundError):
        _declare(tmp_path, conditions_id="ph-revised-001", supersedes_id="does-not-exist")

    lines = _activity_lines(tmp_path)

    assert len(lines) == 2
    assert "outcome=started" in lines[0]
    assert "outcome=error" in lines[1]


def test_activity_logging_failure_never_changes_the_operation_outcome(tmp_path, monkeypatch):  # T-069
    def _boom(*args, **kwargs):
        raise RuntimeError("logging backend unavailable")

    monkeypatch.setattr("molecular.conditions_service.record_activity", _boom)

    declaration = _declare(tmp_path)

    assert declaration.id == "ph-standard-001"
    assert load_conditions(tmp_path, "ph-standard-001") == declaration


# --- thin wrappers (load_conditions/list_conditions do not log) ---


def test_load_conditions_does_not_write_to_the_activity_log(tmp_path):
    declared = _declare(tmp_path)
    log_file = tmp_path / "logs" / "activity.log"
    lines_before = log_file.read_text(encoding="utf-8").splitlines()

    load_conditions(tmp_path, declared.id)

    lines_after = log_file.read_text(encoding="utf-8").splitlines()
    assert lines_after == lines_before


def test_list_conditions_returns_every_declared_record(tmp_path):
    _declare(tmp_path, conditions_id="ph-first-001")
    _declare(tmp_path, conditions_id="ph-second-001")

    declarations = list_conditions(tmp_path)

    assert {d.id for d in declarations} == {"ph-first-001", "ph-second-001"}
