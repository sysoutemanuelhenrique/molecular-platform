def test_retry_does_not_overwrite_the_original_declared_at(tmp_path):  # T-051
    first = _declare(tmp_path)

    # declared_at is generated fresh on every call and is excluded from
    # the retry-equivalence comparison - the recognized retry still
    # returns the original declared_at, discarding its own freshly
    # generated one.
    retried = _declare(tmp_path)

    assert retried.declared_at == first.declared_at


def test_two_distinct_ids_identical_ph_persist_independently(tmp_path):  # T-052
    first = _declare(tmp_path, conditions_id="ph-first-001", ph=_point(Decimal("7.4")))
    second = _declare(tmp_path, conditions_id="ph-second-001", ph=_point(Decimal("7.4")))

    assert first.id != second.id
    assert load_conditions(tmp_path, first.id) == first
    assert load_conditions(tmp_path, second.id) == second


def test_multiple_declarations_coexist_with_no_implicit_ranking(tmp_path):  # T-053
    _declare(tmp_path, conditions_id="ph-first-001")
    _declare(tmp_path, conditions_id="ph-second-001")
    _declare(tmp_path, conditions_id="ph-third-001")

    declarations = list_conditions(tmp_path)

    assert {d.id for d in declarations} == {"ph-first-001", "ph-second-001", "ph-third-001"}
    # No element carries any "current"/"active"/"latest"/rank field of any
    # kind - every record is an ordinary, independently-valid declaration,
    # and the tuple itself implies no ordering preference between them.
    assert not any(hasattr(d, "is_current") or hasattr(d, "rank") for d in declarations)


def test_same_id_in_two_different_project_dirs_are_fully_independent(tmp_path):  # T-054
    project_a = tmp_path / "project-a"
    project_b = tmp_path / "project-b"
    project_a.mkdir()
    project_b.mkdir()

    declared_in_a = _declare(project_a, conditions_id="ph-standard-001", declared_by="Dr. A")
    declared_in_b = _declare(project_b, conditions_id="ph-standard-001", declared_by="Dr. B")

    # Neither call is treated as a retry or a conflict of the other -
    # each project_dir sees only its own fresh creation.
    assert declared_in_a.declared_by == "Dr. A"
    assert declared_in_b.declared_by == "Dr. B"

    # Each record is persisted under, and only under, its own project.
    assert (_conditions_dir(project_a) / "ph-standard-001.yaml").is_file()
    assert (_conditions_dir(project_b) / "ph-standard-001.yaml").is_file()

    # Loading by id from one project never sees the other project's record.
    assert load_conditions(project_a, "ph-standard-001").declared_by == "Dr. A"
    assert load_conditions(project_b, "ph-standard-001").declared_by == "Dr. B"
    assert {d.id for d in list_conditions(project_a)} == {"ph-standard-001"}
    assert {d.id for d in list_conditions(project_b)} == {"ph-standard-001"}


